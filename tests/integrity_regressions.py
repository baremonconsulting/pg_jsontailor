#!/usr/bin/env python3
"""Regression tests for document integrity and generated write paths."""

from __future__ import annotations

import argparse
import json
import re
import subprocess
from pathlib import Path


def quote(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


class TestDatabase:
    def __init__(self, psql: str, database: str):
        self.command = [psql, "-XAt", "-v", "ON_ERROR_STOP=1", "-d", database]

    def run(self, sql: str, check: bool = True) -> subprocess.CompletedProcess[str]:
        result = subprocess.run(self.command, input="\\set VERBOSITY verbose\n" + sql,
                                text=True, capture_output=True)
        if check and result.returncode:
            raise RuntimeError(result.stderr)
        return result

    def value(self, sql: str) -> str:
        return self.run(sql).stdout.strip().splitlines()[-1]

    @staticmethod
    def state(result: subprocess.CompletedProcess[str]) -> str | None:
        match = re.search(r"ERROR:\s+([0-9A-Z]{5}):", result.stderr)
        return match.group(1) if match else None


def create_view(db: TestDatabase, name: str, specification: dict) -> None:
    db.run(f"SELECT jsontailor.create_duality_view({quote(name)},"
           f"{quote(json.dumps(specification))}::jsonb);")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--psql", required=True)
    parser.add_argument("--database", required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    db = TestDatabase(args.psql, args.database)
    results: list[dict[str, str]] = []

    def record(name: str, passed: bool, observed: str) -> None:
        results.append({"name": name, "status": "PASS" if passed else "FAIL",
                        "observed": observed})

    db.run("""DROP SCHEMA IF EXISTS jt_integrity CASCADE; CREATE SCHEMA jt_integrity;
CREATE TABLE jt_integrity.root(id numeric(12,2) PRIMARY KEY, ref_id integer, value text NOT NULL DEFAULT 'new');
CREATE TABLE jt_integrity.ref(id integer PRIMARY KEY, label text);
ALTER TABLE jt_integrity.root ADD CONSTRAINT root_ref_fk FOREIGN KEY(ref_id) REFERENCES jt_integrity.ref(id);
CREATE TABLE jt_integrity.shared_identity(id integer PRIMARY KEY REFERENCES jt_integrity.ref(id), value text);
CREATE TABLE jt_integrity.child(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 parent numeric(12,2) NOT NULL REFERENCES jt_integrity.root(id), value text NOT NULL DEFAULT 'default');
INSERT INTO jt_integrity.ref VALUES(7,'seven');
INSERT INTO jt_integrity.root VALUES(1.00,7,'one');
INSERT INTO jt_integrity.child(parent,value) VALUES(1.00,'first');""")
    spec = {
        "root": {"table": "jt_integrity.root", "key": "id", "fields": {"value": "value"},
                 "insert": True, "update": True, "delete": True},
        "object": {"name": "reference", "table": "jt_integrity.ref", "key": "id",
                   "root_fk": "ref_id", "fields": {"id": "id", "label": "label"}},
        "array": {"name": "items", "table": "jt_integrity.child", "key": "id",
                  "parent_fk": "parent", "fields": {"id": "id", "value": "value"},
                  "insert": True, "update": True, "delete": True},
    }
    create_view(db, "jt_integrity.documents", spec)

    direct = db.run("DELETE FROM jt_integrity.documents WHERE _id=1;", False)
    missing = db.run("SELECT jt_integrity.documents__delete_document(1,NULL);", False)
    stale = db.run("SELECT jt_integrity.documents__delete_document(1,'stale');", False)
    preserved = db.value("SELECT count(*) FROM jt_integrity.root WHERE id=1;")
    etag = db.value("SELECT data#>>'{_metadata,etag}' FROM jt_integrity.documents WHERE _id=1;")
    valid = db.run(f"SELECT jt_integrity.documents__delete_document(1,{quote(etag)});", False)
    record("delete requires expected ETag",
           db.state(direct) == "PT428" and db.state(missing) == "PT428"
           and db.state(stale) == "PT412" and preserved == "1" and valid.returncode == 0,
           f"direct={db.state(direct)},missing={db.state(missing)},stale={db.state(stale)},valid={valid.returncode}")

    db.run("INSERT INTO jt_integrity.root VALUES(1.00,7,'one');"
           "INSERT INTO jt_integrity.child(parent,value) VALUES(1.00,'first');")
    malformed = [
        '{"_id":2,"reference":7,"items":[]}',
        '{"_id":2,"reference":{"id":7,"unknown":1},"items":[]}',
        '{"_id":2,"reference":{"id":7},"items":[{"id":null,"value":"x"}]}',
        '{"_id":2,"reference":{"id":7},"items":[{"unknown":"x"}]}',
    ]
    states = []
    for document in malformed:
        result = db.run(f"INSERT INTO jt_integrity.documents(data) VALUES({quote(document)}::jsonb);", False)
        states.append(db.state(result))
    atomic = db.value("SELECT count(*) FROM jt_integrity.root WHERE id=2;")
    record("malformed nested input is rejected atomically",
           states == ["PT422"] * len(states) and atomic == "0", f"states={states},rows={atomic}")

    key_only = json.loads(json.dumps(spec))
    key_only["array"]["fields"] = {"id": "id"}
    create_view(db, "jt_integrity.key_only_documents", key_only)
    inserted = db.run("""INSERT INTO jt_integrity.key_only_documents(data)
VALUES('{"_id":2,"value":"two","reference":{"id":7},"items":[{},{}]}'::jsonb);""", False)
    child_count = db.value("SELECT count(*) FROM jt_integrity.child WHERE parent=2;")
    record("key-only child mappings accept generated keys",
           inserted.returncode == 0 and child_count == "2", f"insert={inserted.returncode},children={child_count}")

    numeric_doc = db.value("SELECT data::text FROM jt_integrity.documents WHERE _id=1;")
    changed = json.loads(numeric_doc)
    changed["items"][0]["value"] = "changed"
    numeric = db.run("UPDATE jt_integrity.documents SET data=" + quote(json.dumps(changed)) +
                     "::jsonb WHERE _id=1;", False)
    record("numeric keys use typed identity", numeric.returncode == 0,
           f"update={numeric.returncode},state={db.state(numeric)}")

    immutable = json.loads(json.dumps(spec))
    immutable["root"]["update"] = False
    create_view(db, "jt_integrity.immutable_documents", immutable)
    ref_change = db.run("""UPDATE jt_integrity.immutable_documents
SET data=jsonb_set(data,'{reference,id}','8'::jsonb) WHERE _id=1;""", False)
    record("root update policy covers relationship changes",
           db.state(ref_change) == "PT422", f"state={db.state(ref_change)}")

    bad_identity = {
        "root": {"table": "jt_integrity.shared_identity", "key": "id", "fields": {"value": "value"}},
        "object": {"name": "self", "table": "jt_integrity.ref", "key": "id",
                   "root_fk": "id", "fields": {"id": "id"}},
    }
    rejected = db.run("SELECT jsontailor.duality_view_ddl('jt_integrity.bad'," +
                      quote(json.dumps(bad_identity)) + "::jsonb);", False)
    record("root identity cannot also be an object foreign key",
           db.state(rejected) == "22023", f"state={db.state(rejected)}")

    db.run("ALTER TABLE jt_integrity.root RENAME TO root_original;"
           "CREATE TABLE jt_integrity.root(LIKE jt_integrity.root_original INCLUDING ALL);")
    swapped_update = db.run("UPDATE jt_integrity.documents SET data=jsonb_set(data,'{value}','\"wrong\"') WHERE _id=1;", False)
    current_etag = db.value("SELECT data#>>'{_metadata,etag}' FROM jt_integrity.documents WHERE _id=1;")
    swapped_delete = db.run(
        f"SELECT jt_integrity.documents__delete_document(1,{quote(current_etag)});", False)
    original = db.value("SELECT value FROM jt_integrity.root_original WHERE id=1;")
    replacement = db.value("SELECT count(*) FROM jt_integrity.root;")
    record("source relation replacement requires regeneration",
           db.state(swapped_update) == "PT422" and db.state(swapped_delete) == "PT422"
           and original == "one" and replacement == "0",
           f"update={db.state(swapped_update)},delete={db.state(swapped_delete)},original={original},replacement={replacement}")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("".join(json.dumps(row, sort_keys=True) + "\n" for row in results))
    for row in results:
        print(row)
    return 1 if any(row["status"] != "PASS" for row in results) else 0


if __name__ == "__main__":
    raise SystemExit(main())
