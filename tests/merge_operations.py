#!/usr/bin/env python3
"""Exercise the documented native SQL MERGE subset."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import subprocess
import time
from psql_results import tuples, document as returned_document


def literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


class Database:
    def __init__(self, psql: str, database: str):
        self.command = [psql, "-XAt", "-v", "ON_ERROR_STOP=1", "-d", database]

    def run(self, sql: str, check: bool = True) -> subprocess.CompletedProcess[str]:
        result = subprocess.run(self.command, input="\\set VERBOSITY verbose\n" + sql,
                                text=True, capture_output=True)
        if check and result.returncode:
            raise RuntimeError(result.stderr)
        return result

    def value(self, sql: str) -> str:
        result = self.run(sql)
        lines = result.stdout.strip().splitlines()
        if not lines:
            raise RuntimeError(f"query returned no scalar value: {sql}\nstderr: {result.stderr}")
        return lines[-1]

    @staticmethod
    def state(result: subprocess.CompletedProcess[str]) -> str | None:
        match = re.search(r"ERROR:\s+([0-9A-Z]{5}):", result.stderr)
        return match.group(1) if match else None


SPECIFICATION = {
    "root": {"table": "jt_merge.roots", "key": "id", "fields": {"label": "label"},
             "insert": True, "update": True, "delete": True},
    "object": {"name": "reference", "table": "jt_merge.refs", "key": "id",
               "root_fk": "ref_id", "fields": {"id": "id", "name": "name"}, "etag": True},
    "array": {"name": "children", "table": "jt_merge.children", "key": "id",
              "parent_fk": "parent_id", "fields": {"id": "id", "label": "label", "qty": "qty"},
              "insert": True, "update": True, "delete": True},
}


def setup(db: Database, specification: dict | None = None) -> None:
    db.run("""DROP SCHEMA IF EXISTS jt_merge CASCADE; CREATE SCHEMA jt_merge;
CREATE TABLE jt_merge.refs(id integer PRIMARY KEY,name text NOT NULL);
CREATE TABLE jt_merge.roots(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ref_id integer REFERENCES jt_merge.refs(id),label text NOT NULL DEFAULT 'new');
CREATE TABLE jt_merge.children(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 parent_id bigint NOT NULL REFERENCES jt_merge.roots(id),label text NOT NULL DEFAULT 'child',
 qty integer NOT NULL DEFAULT 1 CHECK(qty>0));
INSERT INTO jt_merge.refs VALUES(7,'seven'),(8,'eight');
INSERT INTO jt_merge.roots(id,ref_id,label) VALUES(1,7,'one');
INSERT INTO jt_merge.children(id,parent_id,label,qty) VALUES(10,1,'ten',1);
SELECT pg_catalog.setval(pg_catalog.pg_get_serial_sequence('jt_merge.roots','id'),100);
SELECT pg_catalog.setval(pg_catalog.pg_get_serial_sequence('jt_merge.children','id'),100);""")
    spec = specification or SPECIFICATION
    db.run("SELECT jsontailor.create_duality_view('jt_merge.documents'," +
           literal(json.dumps(spec)) + "::jsonb);")


def document(db: Database, ident: int = 1) -> dict:
    return json.loads(db.value(f"SELECT data::text FROM jt_merge.documents WHERE _id={ident};"))


def merge_sql(source: str, matched: str, unmatched: str = "") -> str:
    return ("MERGE INTO jt_merge.documents AS target USING (" + source + ") AS source(root_id,doc) "
            "ON target._id=source.root_id " + matched + " " + unmatched +
            " RETURNING merge_action(),target._id,target.data;")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--psql", required=True)
    parser.add_argument("--database", required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    db = Database(args.psql, args.database)
    version = int(db.value("SHOW server_version_num;"))
    if version < 170000:
        raise RuntimeError(
            f"MERGE regression suite requires PostgreSQL 17 or newer; server_version_num={version}")
    results: list[dict[str, str]] = []

    def record(name: str, passed: bool, observed: str) -> None:
        row = {"name": name, "status": "PASS" if passed else "FAIL", "observed": observed}
        results.append(row)
        print(row)

    # Mixed update/insert, child reconciliation, defaults and stored RETURNING values.
    setup(db)
    updated = document(db)
    previous = json.loads(json.dumps(updated))
    updated["label"] = "updated"
    updated["children"][0]["qty"] = 2
    updated["children"].append({"label": "generated", "qty": 3})
    inserted = {"_id": 2, "reference": {"id": 8}, "children": [{"qty": 4}]}
    source = "VALUES(1," + literal(json.dumps(updated)) + "::jsonb),(2," + literal(json.dumps(inserted)) + "::jsonb)"
    result = db.run(merge_sql(source,
        "WHEN MATCHED THEN UPDATE SET data=source.doc",
        "WHEN NOT MATCHED THEN INSERT(data) VALUES(source.doc)"), False)
    returned_rows = ["|".join(row) for row in tuples(result, "MERGE", 2, 3)]
    for action, ident, value in tuples(result, "MERGE", 2, 3):
        if action not in {"INSERT", "UPDATE"}:
            raise RuntimeError("unexpected MERGE RETURNING action")
        returned_document(value, document(db, int(ident)), previous if action == "UPDATE" else None)
    actions = sorted(line.split("|", 1)[0] for line in returned_rows)
    state = db.value("SELECT (SELECT label FROM jt_merge.roots WHERE id=1)||':'||"
                     "(SELECT label FROM jt_merge.roots WHERE id=2)||':'||"
                     "(SELECT count(*) FROM jt_merge.children WHERE parent_id IN(1,2));")
    returned_generated = any('"label": "child"' in line and '"id":' in line
                             for line in returned_rows)
    record("mixed actions, defaults and returning",
           result.returncode == 0 and actions == ["INSERT", "UPDATE"] and state == "updated:new:3"
           and returned_generated, f"rc={result.returncode},actions={actions},state={state},generated={returned_generated}")

    # Missing, stale and incomplete replacement documents retain their existing errors.
    setup(db)
    stale = document(db); db.run("UPDATE jt_merge.roots SET label='direct' WHERE id=1;")
    stale["label"] = "stale"
    stale_result = db.run(merge_sql("VALUES(1," + literal(json.dumps(stale)) + "::jsonb)",
        "WHEN MATCHED THEN UPDATE SET data=source.doc"), False)
    missing = document(db); missing.pop("_metadata"); missing["label"] = "missing"
    missing_result = db.run(merge_sql("VALUES(1," + literal(json.dumps(missing)) + "::jsonb)",
        "WHEN MATCHED THEN UPDATE SET data=source.doc"), False)
    incomplete = document(db); incomplete.pop("label")
    incomplete_result = db.run(merge_sql("VALUES(1," + literal(json.dumps(incomplete)) + "::jsonb)",
        "WHEN MATCHED THEN UPDATE SET data=source.doc"), False)
    delete_doc = document(db)
    wrong_delete = json.loads(json.dumps(delete_doc)); wrong_delete["_metadata"]["etag"] = "wrong"
    skipped_delete = db.run(merge_sql("VALUES(1," + literal(json.dumps(wrong_delete)) + "::jsonb)",
        "WHEN MATCHED AND target.data#>>'{_metadata,etag}'=source.doc#>>'{_metadata,etag}' THEN DELETE"), False)
    delete_result = db.run(merge_sql("VALUES(1," + literal(json.dumps(delete_doc)) + "::jsonb)",
        "WHEN MATCHED AND target.data#>>'{_metadata,etag}'=source.doc#>>'{_metadata,etag}' THEN DELETE"), False)
    deleted = tuples(delete_result, "MERGE", 1, 3)[0]
    if deleted[:2] != ["DELETE", "1"]:
        raise RuntimeError("incorrect MERGE DELETE RETURNING identity")
    returned_document(deleted[2], delete_doc)
    if db.value("SELECT count(*) FROM jt_merge.documents WHERE _id=1;") != "0":
        raise RuntimeError("MERGE DELETE did not remove returned preimage")
    record("replacement preconditions",
           [db.state(stale_result), db.state(missing_result), db.state(incomplete_result),
            db.state(delete_result)] == ["PT412", "PT428", "PT422", None]
           and skipped_delete.returncode == 0 and delete_result.returncode == 0,
           str([db.state(stale_result), db.state(missing_result), db.state(incomplete_result),
                db.state(delete_result), skipped_delete.returncode]))

    # An invalid action rolls back every row change made by the statement.
    setup(db)
    valid = document(db); valid["label"] = "must-roll-back"
    invalid = {"_id": 3, "label": "invalid", "reference": {"id": 7},
               "children": [{"label": "bad", "qty": 0}]}
    rollback = db.run(merge_sql(
        "VALUES(1," + literal(json.dumps(valid)) + "::jsonb),(3," + literal(json.dumps(invalid)) + "::jsonb)",
        "WHEN MATCHED THEN UPDATE SET data=source.doc",
        "WHEN NOT MATCHED THEN INSERT(data) VALUES(source.doc)"), False)
    rolled_back = db.value("SELECT label||':'||(SELECT count(*) FROM jt_merge.roots WHERE id=3) FROM jt_merge.roots WHERE id=1;")
    record("statement atomicity", db.state(rollback) == "23514" and rolled_back == "one:0",
           f"state={db.state(rollback)},rows={rolled_back}")

    # DO NOTHING returns no changed row and does not remove targets absent from the source.
    setup(db); db.run("INSERT INTO jt_merge.roots(id,ref_id,label) VALUES(2,7,'two');")
    noop = db.run(merge_sql("SELECT 1," + literal(json.dumps(document(db))) + "::jsonb",
                            "WHEN MATCHED AND source.doc->>'label'='never' THEN UPDATE SET data=source.doc "
                            "WHEN MATCHED THEN DO NOTHING"), False)
    retained = db.value("SELECT count(*) FROM jt_merge.roots;")
    record("do nothing and absent targets", noop.returncode == 0
           and not any(line.startswith(("INSERT|", "UPDATE|")) for line in noop.stdout.splitlines())
           and retained == "2",
           f"rc={noop.returncode},returned={noop.stdout.strip()!r},roots={retained}")

    # Duplicate source keys are deliberately not normalised by the extension.
    setup(db)
    unchanged = document(db)
    duplicate_noop = db.run(merge_sql(
        "VALUES(1," + literal(json.dumps(unchanged)) + "::jsonb),(1," + literal(json.dumps(unchanged)) + "::jsonb)",
        "WHEN MATCHED THEN UPDATE SET data=source.doc"), False)
    first = document(db); second = json.loads(json.dumps(first)); first["label"] = "first"; second["label"] = "second"
    duplicate_change = db.run(merge_sql(
        "VALUES(1," + literal(json.dumps(first)) + "::jsonb),(1," + literal(json.dumps(second)) + "::jsonb)",
        "WHEN MATCHED THEN UPDATE SET data=source.doc"), False)
    duplicate_insert = db.run(merge_sql(
        "VALUES(4,'{\"_id\":4,\"label\":\"a\",\"children\":[]}'::jsonb),"
        "(4,'{\"_id\":4,\"label\":\"b\",\"children\":[]}'::jsonb)",
        "WHEN MATCHED THEN DO NOTHING", "WHEN NOT MATCHED THEN INSERT(data) VALUES(source.doc)"), False)
    duplicate_state = db.value("SELECT label||':'||(SELECT count(*) FROM jt_merge.roots WHERE id=4) FROM jt_merge.roots WHERE id=1;")
    record("duplicate source behaviour",
           duplicate_noop.returncode == 0
           and len([line for line in duplicate_noop.stdout.splitlines() if line.startswith("UPDATE|")]) == 2
           and db.state(duplicate_change) == "PT412" and db.state(duplicate_insert) == "23505"
           and duplicate_state == "one:0",
           f"noop={duplicate_noop.returncode}/"
           f"{len([line for line in duplicate_noop.stdout.splitlines() if line.startswith('UPDATE|')])},"
           f"change={db.state(duplicate_change)},insert={db.state(duplicate_insert)},rows={duplicate_state}")

    # Mapping flags and object ETag settings apply unchanged through MERGE.
    disabled = json.loads(json.dumps(SPECIFICATION)); disabled["root"]["insert"] = False; disabled["root"]["update"] = False
    setup(db, disabled)
    blocked_insert = db.run(merge_sql("VALUES(2,'{\"_id\":2,\"children\":[]}'::jsonb)",
        "WHEN MATCHED THEN DO NOTHING", "WHEN NOT MATCHED THEN INSERT(data) VALUES(source.doc)"), False)
    changed_ref = document(db); changed_ref["reference"] = {"id": 8, "name": "eight"}
    blocked_update = db.run(merge_sql("VALUES(1," + literal(json.dumps(changed_ref)) + "::jsonb)",
        "WHEN MATCHED THEN UPDATE SET data=source.doc"), False)
    array_states = []
    for operation, edit in (
        ("insert", lambda value: value["children"].append({"label": "new", "qty": 1})),
        ("update", lambda value: value["children"][0].update(qty=2)),
        ("delete", lambda value: value.update(children=[])),
    ):
        array_disabled = json.loads(json.dumps(SPECIFICATION)); array_disabled["array"][operation] = False
        setup(db, array_disabled); array_doc = document(db); edit(array_doc)
        array_result = db.run(merge_sql("VALUES(1," + literal(json.dumps(array_doc)) + "::jsonb)",
            "WHEN MATCHED THEN UPDATE SET data=source.doc"), False)
        array_states.append(db.state(array_result))
    no_object_etag = json.loads(json.dumps(SPECIFICATION)); no_object_etag["object"]["etag"] = False
    setup(db, no_object_etag); object_document = document(db); db.run("UPDATE jt_merge.refs SET name='changed' WHERE id=7;")
    object_document["label"] = "allowed"
    object_result = db.run(merge_sql("VALUES(1," + literal(json.dumps(object_document)) + "::jsonb)",
        "WHEN MATCHED THEN UPDATE SET data=source.doc"), False)
    record("operation flags and object ETag",
           db.state(blocked_insert) == "PT422" and db.state(blocked_update) == "PT422"
           and array_states == ["PT422", "PT422", "PT422"] and object_result.returncode == 0,
           f"insert={db.state(blocked_insert)},update={db.state(blocked_update)},"
           f"array={array_states},object={object_result.returncode}")

    # Invoker rights and RLS are retained on the generated MERGE write path.
    setup(db)
    db.run("""DO $$BEGIN IF NOT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='jt_merge_user')
THEN CREATE ROLE jt_merge_user NOLOGIN; END IF; END$$;
GRANT USAGE ON SCHEMA jt_merge TO jt_merge_user;
GRANT SELECT,INSERT,UPDATE,DELETE ON jt_merge.documents TO jt_merge_user;
GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA jt_merge TO jt_merge_user;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA jt_merge TO jt_merge_user;
ALTER TABLE jt_merge.roots ENABLE ROW LEVEL SECURITY;
CREATE POLICY merge_select ON jt_merge.roots FOR SELECT TO jt_merge_user USING(true);
CREATE POLICY merge_update ON jt_merge.roots FOR UPDATE TO jt_merge_user USING(false);""")
    rls_doc = document(db); rls_doc["label"] = "blocked"
    rls = db.run("SET ROLE jt_merge_user;" + merge_sql(
        "VALUES(1," + literal(json.dumps(rls_doc)) + "::jsonb)",
        "WHEN MATCHED THEN UPDATE SET data=source.doc"), False)
    security = db.value("SELECT bool_and(NOT prosecdef) FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='jt_merge';")
    record("invoker rights and RLS", db.state(rls) == "42501" and security == "t",
           f"state={db.state(rls)},invoker={security}")

    # Concurrent NOT MATCHED inserts have native MERGE semantics: one may fail 23505.
    setup(db)
    create_doc = '{"_id":50,"label":"fifty","reference":{"id":7},"children":[]}'
    concurrent_sql = merge_sql("VALUES(50," + literal(create_doc) + "::jsonb)",
        "WHEN MATCHED THEN DO NOTHING", "WHEN NOT MATCHED THEN INSERT(data) VALUES(source.doc)")
    writer = subprocess.Popen(db.command, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                              stderr=subprocess.PIPE, text=True)
    assert writer.stdin
    writer.stdin.write("BEGIN;" + concurrent_sql + "SELECT pg_sleep(1);COMMIT;")
    writer.stdin.close(); time.sleep(.2)
    contender = db.run(concurrent_sql, False)
    writer.wait(timeout=10)
    record("concurrent insert contract", writer.returncode == 0 and db.state(contender) == "23505"
           and db.value("SELECT count(*) FROM jt_merge.roots WHERE id=50;") == "1",
           f"writer={writer.returncode},contender={db.state(contender)}")

    # A client token remains effective across concurrent UPDATE and DELETE; recreation is explicit.
    setup(db); stale_update = document(db); stale_update["label"] = "client"
    writer = subprocess.Popen(db.command, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                              stderr=subprocess.PIPE, text=True)
    assert writer.stdin
    writer.stdin.write("BEGIN;UPDATE jt_merge.roots SET label='concurrent' WHERE id=1;SELECT pg_sleep(1);COMMIT;")
    writer.stdin.close(); time.sleep(.2)
    concurrent = db.run(merge_sql("VALUES(1," + literal(json.dumps(stale_update)) + "::jsonb)",
        "WHEN MATCHED THEN UPDATE SET data=source.doc"), False)
    writer.wait(timeout=10)
    setup(db); stale_delete = document(db)
    writer = subprocess.Popen(db.command, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                              stderr=subprocess.PIPE, text=True)
    assert writer.stdin
    writer.stdin.write("BEGIN;UPDATE jt_merge.roots SET label='concurrent' WHERE id=1;SELECT pg_sleep(1);COMMIT;")
    writer.stdin.close(); time.sleep(.2)
    concurrent_delete = db.run(merge_sql(
        "VALUES(1," + literal(json.dumps(stale_delete)) + "::jsonb)",
        "WHEN MATCHED AND target.data#>>'{_metadata,etag}'=source.doc#>>'{_metadata,etag}' THEN DELETE"), False)
    writer.wait(timeout=10)
    deleted = document(db); etag = deleted["_metadata"]["etag"]
    db.run("SELECT jt_merge.documents__delete_document(1," + literal(etag) + ");")
    recreate = db.run(merge_sql("VALUES(1," + literal(json.dumps(deleted)) + "::jsonb)",
        "WHEN MATCHED THEN UPDATE SET data=source.doc",
        "WHEN NOT MATCHED THEN INSERT(data) VALUES(source.doc)"), False)
    record("concurrent update and explicit recreation",
           db.state(concurrent) == "PT412" and db.state(concurrent_delete) == "PT412"
           and recreate.returncode == 0
           and db.value("SELECT count(*) FROM jt_merge.roots WHERE id=1;") == "1",
           f"update={db.state(concurrent)},delete={db.state(concurrent_delete)},"
           f"recreate={recreate.returncode}")

    # Reused insert/update paths retain nested validation and relation-binding checks.
    setup(db)
    null_child = {"_id": 2, "reference": {"id": 7},
                  "children": [{"id": None, "qty": 1}, {"id": 200, "qty": 1}]}
    invalid_nested = db.run(merge_sql("VALUES(2," + literal(json.dumps(null_child)) + "::jsonb)",
        "WHEN MATCHED THEN DO NOTHING", "WHEN NOT MATCHED THEN INSERT(data) VALUES(source.doc)"), False)
    source_doc = document(db); source_doc["label"] = "wrong-target"
    db.run("ALTER TABLE jt_merge.roots RENAME TO roots_original;"
           "CREATE TABLE jt_merge.roots(LIKE jt_merge.roots_original INCLUDING ALL);")
    swapped = db.run(merge_sql("VALUES(1," + literal(json.dumps(source_doc)) + "::jsonb)",
        "WHEN MATCHED THEN UPDATE SET data=source.doc"), False)
    record("reused path integrity guards", db.state(invalid_nested) == "PT422" and db.state(swapped) == "PT422",
           f"nested={db.state(invalid_nested)},binding={db.state(swapped)}")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("".join(json.dumps(row, sort_keys=True) + "\n" for row in results))
    return 1 if any(row["status"] != "PASS" for row in results) else 0


if __name__ == "__main__":
    raise SystemExit(main())
