#!/usr/bin/env python3
"""PGJT-134 measured least-privilege contract for the documented role."""
import argparse
import json
from pathlib import Path

from security_contract_matrix import Database, quote


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--psql', required=True)
    parser.add_argument('--database', required=True)
    parser.add_argument('--result', type=Path, required=True)
    args = parser.parse_args()
    db = Database(args.psql, args.database)
    rows = []

    def record(name, ok, observed=''):
        rows.append({'id': 'PGJT-134/' + name, 'status': 'PASS' if ok else 'FAIL',
                     'observed': observed})
        args.result.write_text(''.join(json.dumps(row, sort_keys=True) + '\n' for row in rows))
        assert ok, (name, observed)

    spec = {
        'root': {'table': 'jt134.orders', 'key': 'id',
                 'fields': {'status': 'status'}, 'insert': True,
                 'update': True, 'delete': True},
        'object': {'name': 'customer', 'table': 'jt134.customers', 'key': 'id',
                   'root_fk': 'customer_id', 'fields': {'id': 'id', 'name': 'name'},
                   'etag': False},
        'array': {'name': 'items', 'table': 'jt134.items', 'key': 'id',
                  'parent_fk': 'parent', 'fields': {'id': 'id', 'label': 'label'},
                  'insert': True, 'update': True, 'delete': True}}
    db.run('DROP SCHEMA IF EXISTS jt134 CASCADE; DROP ROLE IF EXISTS jt134_app; '
           'CREATE ROLE jt134_app NOLOGIN; CREATE SCHEMA jt134; '
           'CREATE TABLE jt134.customers(id bigint PRIMARY KEY,name text NOT NULL); '
           'CREATE TABLE jt134.orders(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,'
           ' customer_id bigint REFERENCES jt134.customers(id),status text NOT NULL); '
           'CREATE TABLE jt134.items(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,'
           ' parent bigint NOT NULL REFERENCES jt134.orders(id),label text NOT NULL); '
           'CREATE TABLE jt134.serial_keys(id bigserial PRIMARY KEY,label text NOT NULL); '
           'CREATE INDEX items_parent_id ON jt134.items(parent,id); '
           "INSERT INTO jt134.customers VALUES(7,'ACME'); "
           f"SELECT jsontailor.create_duality_view('jt134.documents',{quote(json.dumps(spec))}::jsonb); "
           'REVOKE ALL ON SCHEMA jt134 FROM PUBLIC; '
           'REVOKE ALL ON ALL TABLES IN SCHEMA jt134 FROM PUBLIC; '
           'REVOKE ALL ON ALL FUNCTIONS IN SCHEMA jt134 FROM PUBLIC; '
           'REVOKE ALL ON ALL SEQUENCES IN SCHEMA jt134 FROM PUBLIC; '
           'GRANT USAGE ON SCHEMA jt134 TO jt134_app; '
           'GRANT SELECT,INSERT,UPDATE,DELETE ON jt134.documents TO jt134_app; '
           'GRANT SELECT,INSERT,UPDATE,DELETE ON jt134.orders,jt134.items TO jt134_app; '
           'GRANT SELECT ON jt134.customers TO jt134_app; '
           "SELECT jsontailor.grant_array_reader('jt134.documents','jt134_app',false); "
           "SELECT jsontailor.grant_delete_rpc('jt134.documents','jt134_app',false); "
           'GRANT EXECUTE ON FUNCTION jt134.documents__check() TO jt134_app;')
    try:
        no_sequences = db.value("""SELECT count(*) FROM (VALUES
 ('jt134.orders_id_seq'),('jt134.items_id_seq')) AS s(name)
 WHERE has_sequence_privilege('jt134_app',name,'USAGE')
 OR has_sequence_privilege('jt134_app',name,'SELECT')
 OR has_sequence_privilege('jt134_app',name,'UPDATE');""")
        db.run("""SET ROLE jt134_app;
 INSERT INTO jt134.documents(data) VALUES
 ('{"status":"new","customer":{"id":7},"items":[{"label":"first"}]}'::jsonb);""")
        inserted = db.value("SET ROLE jt134_app; SELECT data::text FROM jt134.documents ORDER BY _id DESC LIMIT 1;")
        doc = json.loads(inserted)
        ident = doc['_id']
        record('identity-insert-needs-no-sequence-grant', no_sequences == '0'
               and doc['items'][0]['label'] == 'first', f'sequence_acl={no_sequences}')
        db.run('GRANT INSERT ON jt134.serial_keys TO jt134_app;')
        serial_without = db.run("SET ROLE jt134_app; INSERT INTO jt134.serial_keys(label) VALUES('x');", False)
        db.run('GRANT USAGE ON SEQUENCE jt134.serial_keys_id_seq TO jt134_app;')
        serial_with = db.run("SET ROLE jt134_app; INSERT INTO jt134.serial_keys(label) VALUES('x');", False)
        record('serial-needs-exact-usage-only', serial_without.returncode != 0
               and serial_with.returncode == 0
               and db.value("SELECT has_sequence_privilege('jt134_app','jt134.serial_keys_id_seq','SELECT');") == 'f',
               serial_without.stderr + serial_with.stderr)
        doc['status'] = 'changed'; doc['items'][0]['label'] = 'changed'
        replaced = db.run(f"SET ROLE jt134_app; UPDATE jt134.documents SET data={quote(json.dumps(doc))}::jsonb "
                          f"WHERE _id={ident};", False)
        record('replacement-with-array', replaced.returncode == 0, replaced.stderr)
        etag = db.value(f"SET ROLE jt134_app; SELECT data#>>'{{_metadata,etag}}' FROM jt134.documents WHERE _id={ident};")
        deleted = db.run(f"SET ROLE jt134_app; SELECT jt134.documents__delete_document({ident},{quote(etag)});", False)
        record('rpc-delete', deleted.returncode == 0
               and db.value(f'SELECT count(*) FROM jt134.orders WHERE id={ident};') == '0', deleted.stderr)
        db.run("INSERT INTO jt134.orders(id,customer_id,status) VALUES(500,7,'base'); "
               "INSERT INTO jt134.items(id,parent,label) VALUES(500,500,'base');")
        base_doc = json.loads(db.value("SELECT data::text FROM jt134.documents WHERE _id=500;"))
        changed_root = json.loads(json.dumps(base_doc)); changed_root['status'] = 'changed'
        changed_child = json.loads(json.dumps(base_doc)); changed_child['items'][0]['label'] = 'changed'
        removed_child = json.loads(json.dumps(base_doc)); removed_child['items'] = []
        base_etag = base_doc['_metadata']['etag']
        cases = [
            ('view-select', 'REVOKE SELECT ON jt134.documents FROM jt134_app',
             'GRANT SELECT ON jt134.documents TO jt134_app', 'SELECT data FROM jt134.documents LIMIT 1'),
            ('source-select', 'REVOKE SELECT ON jt134.orders FROM jt134_app',
             'GRANT SELECT ON jt134.orders TO jt134_app', 'SELECT data FROM jt134.documents LIMIT 1'),
            ('array-reader', 'REVOKE EXECUTE ON FUNCTION jt134.documents__bounded_array(bigint) FROM jt134_app',
             'GRANT EXECUTE ON FUNCTION jt134.documents__bounded_array(bigint) TO jt134_app',
             'SELECT data FROM jt134.documents LIMIT 1'),
            ('root-insert', 'REVOKE INSERT ON jt134.orders FROM jt134_app',
             'GRANT INSERT ON jt134.orders TO jt134_app',
             "INSERT INTO jt134.documents(data) VALUES ('{\"status\":\"x\",\"customer\":{\"id\":7},\"items\":[]}'::jsonb)"),
            ('child-insert', 'REVOKE INSERT ON jt134.items FROM jt134_app',
             'GRANT INSERT ON jt134.items TO jt134_app',
             "INSERT INTO jt134.documents(data) VALUES ('{\"status\":\"x\",\"customer\":{\"id\":7},\"items\":[{\"label\":\"x\"}]}'::jsonb)"),
            ('root-update', 'REVOKE UPDATE ON jt134.orders FROM jt134_app',
             'GRANT UPDATE ON jt134.orders TO jt134_app',
             f"UPDATE jt134.documents SET data={quote(json.dumps(changed_root))}::jsonb WHERE _id=500"),
            ('child-update', 'REVOKE UPDATE ON jt134.items FROM jt134_app',
             'GRANT UPDATE ON jt134.items TO jt134_app',
             f"UPDATE jt134.documents SET data={quote(json.dumps(changed_child))}::jsonb WHERE _id=500"),
            ('child-delete', 'REVOKE DELETE ON jt134.items FROM jt134_app',
             'GRANT DELETE ON jt134.items TO jt134_app',
             f"UPDATE jt134.documents SET data={quote(json.dumps(removed_child))}::jsonb WHERE _id=500"),
            ('view-delete', 'REVOKE DELETE ON jt134.documents FROM jt134_app',
             'GRANT DELETE ON jt134.documents TO jt134_app',
             f"SELECT jt134.documents__delete_document(500,{quote(base_etag)})"),
            ('root-delete', 'REVOKE DELETE ON jt134.orders FROM jt134_app',
             'GRANT DELETE ON jt134.orders TO jt134_app',
             f"SELECT jt134.documents__delete_document(500,{quote(base_etag)})"),
            ('rpc-execute', 'REVOKE EXECUTE ON FUNCTION jt134.documents__delete_document(bigint,text) FROM jt134_app',
             'GRANT EXECUTE ON FUNCTION jt134.documents__delete_document(bigint,text) TO jt134_app',
             f"SELECT jt134.documents__delete_document(500,{quote(base_etag)})"),
            ('health-execute', 'REVOKE EXECUTE ON FUNCTION jt134.documents__check() FROM jt134_app',
             'GRANT EXECUTE ON FUNCTION jt134.documents__check() TO jt134_app',
             'SELECT jt134.documents__check()'),
            ('schema-usage', 'REVOKE USAGE ON SCHEMA jt134 FROM jt134_app',
             'GRANT USAGE ON SCHEMA jt134 TO jt134_app',
             'SELECT jt134.documents__check()'),
        ]
        outcomes = []
        for name, revoke, restore, sql in cases:
            baseline = db.run('BEGIN; SET ROLE jt134_app; ' + sql + '; ROLLBACK;', False)
            db.run(revoke)
            result = db.run('BEGIN; SET ROLE jt134_app; ' + sql + '; ROLLBACK;', False)
            db.run(restore)
            outcomes.append((name, baseline.returncode == 0 and result.returncode != 0,
                             'baseline=' + (db.state(baseline) or 'success')
                             + ', revoked=' + (db.state(result) or 'unknown')))
        record('each-documented-capability-is-required', all(ok for _, ok, _ in outcomes), repr(outcomes))
    finally:
        db.run('DROP SCHEMA IF EXISTS jt134 CASCADE; DROP ROLE IF EXISTS jt134_app;', False)


if __name__ == '__main__':
    main()
