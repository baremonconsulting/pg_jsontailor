import subprocess
from pathlib import Path


SHAPES = ("root", "root_object", "root_array", "full")
OPERATIONS = ("insert", "read", "update", "direct_delete", "rpc_delete",
              "merge_insert", "merge_update", "merge_delete")
EXPECTED_SHAPES = ("root", "root_object", "root_array", "full")
EXPECTED_OPERATIONS = ("insert", "read", "update", "direct_delete", "rpc_delete",
                       "merge_insert", "merge_update", "merge_delete")


def quote(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


class Database:
    def __init__(self, psql: str, database: str):
        self.command = [psql, "-XAt", "-v", "ON_ERROR_STOP=1", "-d", database]

    def run(self, sql: str, check: bool = True) -> subprocess.CompletedProcess[str]:
        result = subprocess.run(self.command, input="\\set VERBOSITY verbose\n" + sql,
                                text=True, capture_output=True)
        if check and result.returncode:
            raise RuntimeError(result.stderr)
        return result

    def value(self, sql: str) -> str:
        result = self.run(sql)
        values = result.stdout.strip().splitlines()
        if not values:
            raise RuntimeError(f"query returned no value: {sql}\n{result.stderr}")
        return values[-1]

    @staticmethod
    def state(result: subprocess.CompletedProcess[str]) -> str | None:
        match = re.search(r"ERROR:\s+([0-9A-Z]{5}):", result.stderr)
        return match.group(1) if match else None


def has_object(shape: str) -> bool:
    return shape in ("root_object", "full")


def has_array(shape: str) -> bool:
    return shape in ("root_array", "full")


def specification(shape: str, *, root_flags=(True, True, True),
                  array_flags=(True, True, True), object_etag=True) -> dict:
    schema = f"jt_shape_{shape}"
    spec: dict = {
        "root": {"table": f"{schema}.root", "key": "id",
                 "fields": {"label": "label"},
                 "insert": root_flags[0], "update": root_flags[1],
                 "delete": root_flags[2]}}
    if has_object(shape):
        spec["object"] = {
            "name": "detail", "table": f"{schema}.detail", "key": "id",
            "root_fk": "detail_id", "fields": {"id": "id", "name": "name"},
            "etag": object_etag}
    if has_array(shape):
        spec["array"] = {
            "name": "items", "table": f"{schema}.item", "key": "id",
            "parent_fk": "parent", "fields": {"id": "id", "label": "label"},
            "insert": array_flags[0], "update": array_flags[1],
            "delete": array_flags[2]}
    return spec


def setup(db: Database, shape: str, **options) -> None:
    schema = f"jt_shape_{shape}"
    detail_column = ",detail_id integer REFERENCES " + schema + ".detail(id)" \
        if has_object(shape) else ""
    db.run(f"DROP SCHEMA IF EXISTS {schema} CASCADE; CREATE SCHEMA {schema};")
    if has_object(shape):
        db.run(f"CREATE TABLE {schema}.detail(id integer PRIMARY KEY,name text NOT NULL);"
               f"INSERT INTO {schema}.detail VALUES(7,'seven'),(8,'eight');")
    db.run(f"CREATE TABLE {schema}.root("
           f"id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
           f"label text NOT NULL DEFAULT 'root-default'{detail_column});")
    if has_array(shape):
        db.run(f"CREATE TABLE {schema}.item("
               "id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
               f"parent bigint NOT NULL REFERENCES {schema}.root(id),"
               "label text NOT NULL DEFAULT 'item-default');")
    root_values = "1,'one'" + (",7" if has_object(shape) else "")
    db.run(f"INSERT INTO {schema}.root VALUES({root_values});"
           f"SELECT setval(pg_get_serial_sequence('{schema}.root','id'),100);")
    if has_array(shape):
        db.run(f"INSERT INTO {schema}.item(id,parent,label) VALUES(10,1,'ten');"
               f"SELECT setval(pg_get_serial_sequence('{schema}.item','id'),100);")
    spec = specification(shape, **options)
    db.run(f"SELECT jsontailor.create_duality_view('{schema}.documents',"
           f"{quote(json.dumps(spec))}::jsonb);")


def new_document(shape: str, identity: int | None, *, populated=True) -> dict:
    document: dict = {}
    if identity is not None:
        document["_id"] = identity
    if has_object(shape):
        document["detail"] = {"id": 7, "name": "seven"}
    if has_array(shape):
        document["items"] = ([{}] if populated else [])
    return document


def read(db: Database, shape: str, identity: int) -> dict:
    return json.loads(db.value(
        f"SELECT data::text FROM jt_shape_{shape}.documents WHERE _id={identity};"))


def merge(db: Database, shape: str, identity: int, document: dict,
          matched: str, unmatched: str = "") -> subprocess.CompletedProcess[str]:
    schema = f"jt_shape_{shape}"
    sql = (f"MERGE INTO {schema}.documents d USING (VALUES ({identity},"
           f"{quote(json.dumps(document))}::jsonb)) s(id,data) ON d._id=s.id "
           f"{matched} {unmatched} RETURNING merge_action(),d._id,d.data;")
    return db.run(sql, False)


def operation_matrix(db: Database, record) -> None:
    outcomes = []
    for shape in SHAPES:
        schema = f"jt_shape_{shape}"
        setup(db, shape)

        inserted = db.run(f"INSERT INTO {schema}.documents(data) VALUES("
                          f"{quote(json.dumps(new_document(shape, 2)))}::jsonb) "
                          "RETURNING data::text;", False)
        inserted_doc = read(db, shape, 2)
        insert_ok = (inserted.returncode == 0
                     and inserted_doc["label"] == "root-default"
                     and (not has_array(shape)
                          or (len(inserted_doc["items"]) == 1
                              and inserted_doc["items"][0]["label"] == "item-default"
                              and isinstance(inserted_doc["items"][0]["id"], int))))
        read_ok = (inserted_doc["_id"] == 2
                   and (not has_object(shape) or inserted_doc["detail"]["id"] == 7)
                   and (not has_array(shape) or len(inserted_doc["items"]) == 1))

        current = read(db, shape, 1)
        current["label"] = "updated"
        if has_array(shape):
            current["items"][0]["label"] = "updated-item"
            current["items"].append({})
        updated = db.run(f"UPDATE {schema}.documents SET data="
                         f"{quote(json.dumps(current))}::jsonb WHERE _id=1;", False)
        updated_doc = read(db, shape, 1)
        update_ok = (updated.returncode == 0 and updated_doc["label"] == "updated"
                     and (not has_array(shape)
                          or [item["label"] for item in updated_doc["items"]]
                          == ["updated-item", "item-default"]))

        direct_etag = inserted_doc["_metadata"]["etag"]
        direct = db.run(f"DELETE FROM {schema}.documents WHERE _id=2 AND "
                        f"data#>>'{{_metadata,etag}}'={quote(direct_etag)};", False)
        direct_ok = direct.returncode == 0 and db.value(
            f"SELECT count(*) FROM {schema}.root WHERE id=2;") == "0"

        db.run(f"INSERT INTO {schema}.documents(data) VALUES("
               f"{quote(json.dumps(new_document(shape, 3, populated=False)))}::jsonb);")
        rpc_etag = read(db, shape, 3)["_metadata"]["etag"]
        rpc = db.run(f"SELECT {schema}.documents__delete_document(3,"
                     f"{quote(rpc_etag)});", False)
        rpc_ok = rpc.returncode == 0 and db.value(
            f"SELECT count(*) FROM {schema}.root WHERE id=3;") == "0"

        merge_insert_doc = new_document(shape, 4)
        merged_insert = merge(db, shape, 4, merge_insert_doc,
                              "WHEN MATCHED THEN DO NOTHING",
                              "WHEN NOT MATCHED THEN INSERT(data) VALUES(s.data)")
        merge_insert_read = read(db, shape, 4)
        merge_insert_ok = (merged_insert.returncode == 0
                           and merge_insert_read["label"] == "root-default"
                           and (not has_object(shape)
                                or merge_insert_read["detail"]
                                == {"id": 7, "name": "seven"})
                           and (not has_array(shape)
                                or (len(merge_insert_read["items"]) == 1
                                    and merge_insert_read["items"][0]["label"]
                                    == "item-default"
                                    and isinstance(merge_insert_read["items"][0]["id"], int))))

        merge_update_doc = read(db, shape, 1)
        merge_update_doc["label"] = "merge-updated"
        merged_update = merge(db, shape, 1, merge_update_doc,
                              "WHEN MATCHED THEN UPDATE SET data=s.data")
        merge_update_read = read(db, shape, 1)
        merge_update_ok = (merged_update.returncode == 0
                           and merge_update_read["label"] == "merge-updated"
                           and (not has_object(shape)
                                or merge_update_read["detail"]
                                == {"id": 7, "name": "seven"})
                           and (not has_array(shape)
                                or [item["label"] for item in merge_update_read["items"]]
                                == ["updated-item", "item-default"]))

        merge_delete_doc = read(db, shape, 4)
        merged_delete = merge(
            db, shape, 4, merge_delete_doc,
            "WHEN MATCHED AND d.data#>>'{_metadata,etag}'="
            "s.data#>>'{_metadata,etag}' THEN DELETE")
        merge_delete_ok = (merged_delete.returncode == 0 and db.value(
            f"SELECT count(*) FROM {schema}.root WHERE id=4;") == "0")

        outcomes.append((shape, insert_ok, read_ok, update_ok, direct_ok, rpc_ok,
                         merge_insert_ok, merge_update_ok, merge_delete_ok))

    record("PGJT-45/shape-operation-matrix",
           tuple(row[0] for row in outcomes) == EXPECTED_SHAPES
           and OPERATIONS == EXPECTED_OPERATIONS
           and all(len(row) == 1 + len(EXPECTED_OPERATIONS) and all(row[1:])
                   for row in outcomes), repr(outcomes))


def flag_matrix(db: Database, record) -> None:
    outcomes = []
    for position, operation in enumerate(("insert", "update", "delete")):
        flags = [True, True, True]
        flags[position] = False
        setup(db, "root", root_flags=tuple(flags))
        schema = "jt_shape_root"
        if operation == "insert":
            result = db.run(f"INSERT INTO {schema}.documents(data) "
                            "VALUES('{\"_id\":2}'::jsonb);", False)
        elif operation == "update":
            document = read(db, "root", 1)
            document["label"] = "blocked"
            result = db.run(f"UPDATE {schema}.documents SET data="
                            f"{quote(json.dumps(document))}::jsonb WHERE _id=1;", False)
        else:
            result = db.run(f"DELETE FROM {schema}.documents WHERE _id=1;", False)
        state = db.value(f"SELECT count(*)::text||':'||label FROM {schema}.root "
                         "GROUP BY label ORDER BY label LIMIT 1;")
        outcomes.append((f"root-{operation}", db.state(result), state))

    for position, operation in enumerate(("insert", "update", "delete")):
        flags = [True, True, True]
        flags[position] = False
        setup(db, "root_array", array_flags=tuple(flags))
        document = read(db, "root_array", 1)
        if operation == "insert":
            document["items"].append({})
        elif operation == "update":
            document["items"][0]["label"] = "blocked"
        else:
            document["items"] = []
        result = db.run("UPDATE jt_shape_root_array.documents SET data=" +
                        quote(json.dumps(document)) + "::jsonb WHERE _id=1;", False)
        state = db.value("SELECT count(*)::text||':'||min(label) "
                         "FROM jt_shape_root_array.item WHERE parent=1;")
        outcomes.append((f"array-{operation}", db.state(result), state))

    expected = (("root-insert", "PT422", "1:one"),
                ("root-update", "PT422", "1:one"),
                ("root-delete", "PT422", "1:one"),
                ("array-insert", "PT422", "1:ten"),
                ("array-update", "PT422", "1:ten"),
                ("array-delete", "PT422", "1:ten"))
    record("PGJT-45/operation-flags", tuple(outcomes) == expected, repr(outcomes))


def etag_matrix(db: Database, record) -> None:
    outcomes = []
    for enabled in (True, False):
        setup(db, "root_object", object_etag=enabled)
        document = read(db, "root_object", 1)
        db.run("UPDATE jt_shape_root_object.detail SET name='changed' WHERE id=7;")
        document["label"] = "client"
        if not enabled:
            document["detail"]["name"] = "changed"
        result = db.run("UPDATE jt_shape_root_object.documents SET data=" +
                        quote(json.dumps(document)) + "::jsonb WHERE _id=1;", False)
        label = db.value("SELECT label FROM jt_shape_root_object.root WHERE id=1;")
        outcomes.append((enabled, db.state(result), result.returncode, label))
    record("PGJT-45/object-etag-modes",
           outcomes == [(True, "PT412", 3, "one"), (False, None, 0, "client")],
           repr(outcomes))


