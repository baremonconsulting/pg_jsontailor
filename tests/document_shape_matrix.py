def atomicity_matrix(db: Database, record) -> None:
    outcomes = []
    for shape in SHAPES:
        setup(db, shape)
        schema = f"jt_shape_{shape}"
        valid = new_document(shape, 2)
        invalid = new_document(shape, 3)
        invalid["unexpected"] = True
        statement = (f"INSERT INTO {schema}.documents(data) VALUES("
                     f"{quote(json.dumps(valid))}::jsonb),("
                     f"{quote(json.dumps(invalid))}::jsonb);")
        inserted = db.run(statement, False)
        rows = db.value(f"SELECT count(*) FROM {schema}.root;")

        db.run(f"INSERT INTO {schema}.documents(data) VALUES("
               f"{quote(json.dumps(new_document(shape, 2)))}::jsonb);")
        first = read(db, shape, 1)
        second = read(db, shape, 2)
        valid_update = json.loads(json.dumps(first))
        valid_update["label"] = "must-roll-back"
        invalid_update = json.loads(json.dumps(second))
        invalid_update.pop("label")
        updated = db.run(
            f"UPDATE {schema}.documents SET data=CASE WHEN _id=1 THEN "
            f"{quote(json.dumps(valid_update))}::jsonb ELSE "
            f"{quote(json.dumps(invalid_update))}::jsonb END WHERE _id IN(1,2);",
            False)
        label = db.value(f"SELECT string_agg(label,',' ORDER BY id) FROM {schema}.root;")
        merge_valid = read(db, shape, 1)
        merge_valid["label"] = "merge-must-roll-back"
        merge_invalid = new_document(shape, 3)
        merge_invalid["unexpected"] = True
        merged = db.run(
            f"MERGE INTO {schema}.documents d USING (VALUES "
            f"(1,{quote(json.dumps(merge_valid))}::jsonb),"
            f"(3,{quote(json.dumps(merge_invalid))}::jsonb)) s(id,data) "
            "ON d._id=s.id WHEN MATCHED THEN UPDATE SET data=s.data "
            "WHEN NOT MATCHED THEN INSERT(data) VALUES(s.data);", False)
        merge_state = db.value(
            f"SELECT string_agg(label,',' ORDER BY id)||':'||"
            f"(SELECT count(*) FROM {schema}.root WHERE id=3) FROM {schema}.root;")
        outcomes.append((shape, db.state(inserted), rows, db.state(updated), label,
                         db.state(merged), merge_state))
    record("PGJT-45/failure-atomicity",
           tuple(row[0] for row in outcomes) == EXPECTED_SHAPES
           and all(state == "PT422" and rows == "1" and update_state == "PT422"
                   and label == "one,root-default" and merge_status == "PT422"
                   and merge_state == "one,root-default:0"
                   for _shape, state, rows, update_state, label, merge_status,
                   merge_state in outcomes),
           repr(outcomes))


def insert_column_identity_matrix(db: Database, record) -> None:
    """PGJT-115 rejects an unconfirmed column identity without changing rows."""
    outcomes = []
    for shape in SHAPES:
        setup(db, shape)
        schema = f"jt_shape_{shape}"
        tables = ["root"] + (["detail"] if has_object(shape) else []) + (
            ["item"] if has_array(shape) else [])

        def snapshot():
            entries = ",".join(
                f"{quote(table)},(SELECT jsonb_agg(to_jsonb(t) ORDER BY id) "
                f"FROM {schema}.{table} t)" for table in tables)
            return db.value(f"SELECT jsonb_build_object({entries})::text;")

        def insertion(column_id, document):
            column = "NULL" if column_id is None else str(column_id)
            return (f"INSERT INTO {schema}.documents(_id,data) VALUES({column},"
                    f"{quote(json.dumps(document))}::jsonb) RETURNING data::text;")

        rejected = (
            ("column-only", 5000, new_document(shape, None, populated=False)),
            ("different-identities", 5001, new_document(shape, 5002, populated=False)),
            ("null-document-identity", 5003,
             {**new_document(shape, None, populated=False), "_id": None}),
        )
        for name, column_id, candidate in rejected:
            before = snapshot()
            failed = db.run(insertion(column_id, candidate), False)
            outcomes.append((shape, name, db.state(failed) == "PT422"
                             and before == snapshot(), db.state(failed)))

        accepted = (
            ("matching-identities", 5010, new_document(shape, 5010, populated=False), 5010),
            ("generated-identity", None, new_document(shape, None, populated=False), None),
            ("null-column-explicit-document", None,
             new_document(shape, 5011, populated=False), 5011),
        )
        for name, column_id, candidate, expected_id in accepted:
            result = db.run(insertion(column_id, candidate), False)
            lines = [line for line in result.stdout.splitlines() if line.startswith("{")]
            returned = json.loads(lines[-1]) if lines else {}
            observed_id = returned.get("_id")
            identity_ok = (observed_id == expected_id if expected_id is not None else
                           type(observed_id) is int and 100 < observed_id < 5000)
            persisted = (identity_ok and db.value(
                f"SELECT count(*) FROM {schema}.root WHERE id={observed_id};") == "1")
            outcomes.append((shape, name, result.returncode == 0 and identity_ok
                             and persisted and returned.get("label") == "root-default",
                             f"state={db.state(result)},id={observed_id}"))

        # Omitting the column altogether retains the existing document-ID path.
        explicit = new_document(shape, 5020, populated=False)
        result = db.run(f"INSERT INTO {schema}.documents(data) VALUES("
                        f"{quote(json.dumps(explicit))}::jsonb);", False)
        outcomes.append((shape, "document-only", result.returncode == 0 and db.value(
            f"SELECT count(*) FROM {schema}.root WHERE id=5020;") == "1", db.state(result)))
        merged = merge(db, shape, 5021, new_document(shape, 5021, populated=False),
                       "WHEN MATCHED THEN DO NOTHING",
                       "WHEN NOT MATCHED THEN INSERT(data) VALUES(s.data)")
        outcomes.append((shape, "merge-data-only", merged.returncode == 0 and db.value(
            f"SELECT count(*) FROM {schema}.root WHERE id=5021;") == "1", db.state(merged)))

        before = snapshot()
        matching = new_document(shape, 5030, populated=False)
        missing = new_document(shape, None, populated=False)
        failed = db.run(f"INSERT INTO {schema}.documents(_id,data) VALUES"
                        f"(5030,{quote(json.dumps(matching))}::jsonb),"
                        f"(5031,{quote(json.dumps(missing))}::jsonb);", False)
        outcomes.append((shape, "multirow-atomic", db.state(failed) == "PT422"
                         and before == snapshot(), db.state(failed)))
    record("PGJT-115/insert-column-identity",
           len(outcomes) == len(EXPECTED_SHAPES) * 9 and all(row[2] for row in outcomes),
           repr(outcomes))


def column_identity_statement(shape: str, path: str, column_id: int | None,
                              document: dict) -> str:
    """Use the real SQL entry points, including COPY's text protocol."""
    target = f"jt_shape_{shape}.documents"
    column = "NULL::bigint" if column_id is None else str(column_id) + "::bigint"
    payload = quote(json.dumps(document)) + "::jsonb"
    if path == "merge_insert":
        return (f"MERGE INTO {target} d USING (VALUES ({column},{payload})) s(id,data) "
                "ON false WHEN NOT MATCHED THEN INSERT(_id,data) VALUES(s.id,s.data);")
    if path == "copy":
        field = json.dumps(document).replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n")
        copy_id = "\\N" if column_id is None else str(column_id)
        return f"COPY {target} (_id,data) FROM STDIN;\n{copy_id}\t{field}\n\\.\n"
    if path == "update":
        return f"UPDATE {target} SET _id={column},data={payload} WHERE _id=1;"
    if path == "merge_update":
        return (f"MERGE INTO {target} d USING (VALUES (1,{column},{payload})) s(id,new_id,data) "
                "ON d._id=s.id WHEN MATCHED THEN UPDATE SET _id=s.new_id,data=s.data;")
    raise ValueError("unsupported column identity path: " + path)


def column_identity_paths(db: Database, record) -> None:
    """PGJT-146: INSERT-column semantics also apply to MERGE/COPY; IDs are immutable."""
    outcomes, mutations = [], []
    missing_guard = ("IF NEW._id IS NOT NULL AND NOT (doc?'_id') THEN RAISE EXCEPTION "
                     "USING ERRCODE='PT422',MESSAGE='_id column requires _id in the document';END IF;")
    for shape in SHAPES:
        setup(db, shape)
        schema = f"jt_shape_{shape}"
        tables = ["root"] + (["detail"] if has_object(shape) else []) + (
            ["item"] if has_array(shape) else [])

        def snapshot():
            return db.value("SELECT jsonb_build_object(" + ",".join(
                f"{quote(table)},(SELECT jsonb_agg(to_jsonb(t) ORDER BY id) FROM {schema}.{table} t)"
                for table in tables) + ")::text;")

        for path_index, path in enumerate(("merge_insert", "copy")):
            base = 6000 + 100 * path_index
            cases = (
                ("column-only", base, new_document(shape, None, populated=False), False),
                ("different", base + 1, new_document(shape, base + 2, populated=False), False),
                ("null-document", base + 3,
                 {**new_document(shape, None, populated=False), "_id": None}, False),
                ("matching", base + 4, new_document(shape, base + 4, populated=False), True),
                ("generated", None, new_document(shape, None, populated=False), True),
                ("null-column", None, new_document(shape, base + 5, populated=False), True),
            )
            for name, identity, document, allowed in cases:
                before = snapshot()
                result = db.run(column_identity_statement(shape, path, identity, document), False)
                if allowed:
                    prior_ids = {row["id"] for row in json.loads(before)["root"]}
                    added = [row for row in json.loads(snapshot())["root"] if row["id"] not in prior_ids]
                    ok = (result.returncode == 0 and len(added) == 1
                          and added[0]["label"] == "root-default"
                          and (added[0]["id"] == document["_id"] if "_id" in document else
                               type(added[0]["id"]) is int and 100 < added[0]["id"] < 6000))
                else:
                    ok = db.state(result) == "PT422" and before == snapshot()
                outcomes.append((shape, path, name, ok, db.state(result)))

            # A two-row statement must not retain its first valid row when the
            # second row has an unconfirmed column identity.
            valid = new_document(shape, base + 20, populated=False)
            invalid = new_document(shape, None, populated=False)
            if path == "merge_insert":
                statement = (f"MERGE INTO {schema}.documents d USING (VALUES "
                    f"({base + 20},{quote(json.dumps(valid))}::jsonb),"
                    f"({base + 21},{quote(json.dumps(invalid))}::jsonb)) s(id,data) "
                    "ON false WHEN NOT MATCHED THEN INSERT(_id,data) VALUES(s.id,s.data);")
            else:
                statement = (f"COPY {schema}.documents (_id,data) FROM STDIN;\n"
                             f"{base + 20}\t{json.dumps(valid)}\n"
                             f"{base + 21}\t{json.dumps(invalid)}\n\\.\n")
            before = snapshot()
            result = db.run(statement, False)
            outcomes.append((shape, path, "multirow-atomic", db.state(result) == "PT422"
                             and before == snapshot(), db.state(result)))

        for path in ("update", "merge_update"):
            for name, identity, document_id, allowed in (
                    ("same", 1, 1, True), ("column-changed", 9000, 1, False),
                    ("column-null", None, 1, False), ("both-changed", 9000, 9000, False)):
                document = read(db, shape, 1)
                document["_id"], document["label"] = document_id, path + "-" + name
                before = snapshot()
                result = db.run(column_identity_statement(shape, path, identity, document), False)
                ok = (result.returncode == 0 and read(db, shape, 1)["label"] == document["label"]) \
                    if allowed else db.state(result) == "PT422" and before == snapshot()
                outcomes.append((shape, path, name, ok, db.state(result)))

        definition = db.value(f"SELECT encode(convert_to(pg_get_functiondef("
                              f"'{schema}.documents__insert()'::regprocedure),'UTF8'),'hex');")
        original = bytes.fromhex(definition).decode()
        if original.count(missing_guard) != 1:
            raise RuntimeError("PGJT-146 INSERT identity mutation target differs")
        mutant = original.replace(missing_guard, "")
        mutant_ddl = mutant.replace("CREATE FUNCTION", "CREATE OR REPLACE FUNCTION", 1).rstrip().rstrip(";") + ";"
        for path in ("merge_insert", "copy"):
            before = snapshot()
            # Confine the generated-function mutation and its unsafe write to
            # one rolled-back transaction; no product source is edited.
            result = db.run("BEGIN;\n" + mutant_ddl
                            + "\n" + column_identity_statement(shape, path, 9900,
                                new_document(shape, None, populated=False))
                            + "\nSELECT 'PGJT-146-MUTANT-ACCEPTED';\nROLLBACK;", False)
            mutations.append((shape, path, result.returncode == 0
                              and "PGJT-146-MUTANT-ACCEPTED" in result.stdout.splitlines()
                              and before == snapshot()
                              and db.value(f"SELECT encode(convert_to(pg_get_functiondef("
                                  f"'{schema}.documents__insert()'::regprocedure),'UTF8'),'hex');") == definition))
    record("PGJT-146/column-identity-paths", len(outcomes) == len(SHAPES) * 22
           and all(row[3] for row in outcomes), repr(outcomes))
    record("PGJT-146/insert-identity-mutation", len(mutations) == len(SHAPES) * 2
           and all(row[2] for row in mutations), repr(mutations))


def deferrable_merge_matrix(db: Database, record) -> None:
    schema = "jt_shape_deferrable"
    db.run(f"DROP SCHEMA IF EXISTS {schema} CASCADE; CREATE SCHEMA {schema};"
           f"CREATE TABLE {schema}.root(id integer PRIMARY KEY,value text NOT NULL);"
           f"CREATE TABLE {schema}.child("
           "id integer,parent integer NOT NULL REFERENCES " + schema + ".root(id),"
           "value text NOT NULL DEFAULT 'default',"
           "CONSTRAINT child_pkey PRIMARY KEY(id) DEFERRABLE INITIALLY IMMEDIATE,"
           "CONSTRAINT child_value_key UNIQUE(value));")
    spec = {
        "root": {"table": f"{schema}.root", "key": "id",
                 "fields": {"value": "value"}, "insert": True,
                 "update": True, "delete": True},
        "array": {"name": "items", "table": f"{schema}.child", "key": "id",
                  "parent_fk": "parent", "fields": {"id": "id", "value": "value"},
                  "insert": True, "update": True, "delete": True}}
    db.run(f"SELECT jsontailor.create_duality_view('{schema}.documents',"
           f"{quote(json.dumps(spec))}::jsonb);")

    initial = db.run(
        f"INSERT INTO {schema}.documents(data) VALUES "
        "('{\"_id\":1,\"value\":\"one\",\"items\":["
        "{\"id\":10,\"value\":\"v10\"}]}'::jsonb),"
        "('{\"_id\":2,\"value\":\"two\",\"items\":["
        "{\"id\":20,\"value\":\"v20\"}]}'::jsonb);", False)
    merge_insert = merge(
        db, "deferrable", 3,
        {"_id": 3, "value": "three", "items": [{"id": 30, "value": "v30"}]},
        "WHEN MATCHED THEN DO NOTHING",
        "WHEN NOT MATCHED THEN INSERT(data) VALUES(s.data)")
    inserted = json.loads(db.value(
        f"SELECT data::text FROM {schema}.documents WHERE _id=3;"))

    update_doc = json.loads(db.value(
        f"SELECT data::text FROM {schema}.documents WHERE _id=1;"))
    update_doc["value"] = "one-updated"
    update_doc["items"].append({"id": 11, "value": "v11"})
    merge_update = merge(db, "deferrable", 1, update_doc,
                         "WHEN MATCHED THEN UPDATE SET data=s.data")
    updated = json.loads(db.value(
        f"SELECT data::text FROM {schema}.documents WHERE _id=1;"))

    conflict_doc = json.loads(json.dumps(updated))
    conflict_doc["value"] = "must-roll-back"
    conflict_doc["items"].append({"id": 20, "value": "foreign"})
    merge_conflict = merge(db, "deferrable", 1, conflict_doc,
                           "WHEN MATCHED THEN UPDATE SET data=s.data")
    conflict_state = db.value(
        f"SELECT (SELECT value FROM {schema}.root WHERE id=1)||':'||"
        f"(SELECT count(*) FROM {schema}.child WHERE parent=1)||':'||"
        f"(SELECT parent FROM {schema}.child WHERE id=20);")

    delete_doc = inserted
    merge_delete = merge(
        db, "deferrable", 3, delete_doc,
        "WHEN MATCHED AND d.data#>>'{_metadata,etag}'="
        "s.data#>>'{_metadata,etag}' THEN DELETE")
    deleted = db.value(f"SELECT count(*) FROM {schema}.root WHERE id=3;")

    record(
        "PGJT-45/deferrable-merge-matrix",
        initial.returncode == 0
        and merge_insert.returncode == 0
        and inserted["value"] == "three"
        and inserted["items"] == [{"id": 30, "value": "v30"}]
        and merge_update.returncode == 0
        and updated["value"] == "one-updated"
        and updated["items"] == [{"id": 10, "value": "v10"},
                                 {"id": 11, "value": "v11"}]
        and db.state(merge_conflict) == "PT422"
        and conflict_state == "one-updated:2:2"
        and merge_delete.returncode == 0 and deleted == "0",
        f"initial={initial.returncode},insert={merge_insert.returncode},"
        f"update={merge_update.returncode},conflict={db.state(merge_conflict)},"
        f"state={conflict_state},delete={merge_delete.returncode}/{deleted}")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--psql", required=True)
    parser.add_argument("--database", required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    db = Database(args.psql, args.database)
    results = []

    def record(name: str, passed: bool, observed: str) -> None:
        results.append({"name": name, "status": "PASS" if passed else "FAIL",
                        "observed": observed})

    operation_matrix(db, record)
    flag_matrix(db, record)
    etag_matrix(db, record)
    identity_default_matrix(db, record)
    atomicity_matrix(db, record)
    deferrable_merge_matrix(db, record)
    insert_column_identity_matrix(db, record)
    column_identity_paths(db, record)
    args.output.write_text("".join(json.dumps(row, sort_keys=True) + "\n"
                                   for row in results))
    for row in results:
        print(f"{row['status']}: {row['name']} ({row['observed']})")
    return 0 if all(row["status"] == "PASS" for row in results) else 1


