-- WARNING: DISPOSABLE DATABASE ONLY. The next statement destroys the shop
-- schema and every dependent object, including existing data, with CASCADE.

DROP SCHEMA IF EXISTS shop CASCADE;
CREATE SCHEMA shop;

CREATE TABLE shop.customers (
    customer_id bigint PRIMARY KEY,
    name        text   NOT NULL
);

CREATE TABLE shop.orders (
    order_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint REFERENCES shop.customers (customer_id),
    status      text   NOT NULL DEFAULT 'new',
    created_at  date   NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE shop.order_items (
    item_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   bigint NOT NULL REFERENCES shop.orders (order_id),
    product    text   NOT NULL,
    quantity   integer NOT NULL CHECK (quantity > 0),
    unit_price numeric(12,2) NOT NULL
);
CREATE INDEX order_items_order_id_idx ON shop.order_items (order_id);

